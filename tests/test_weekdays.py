#!/usr/bin/env python3
"""
Проверка правил, которые работают ПОСЛЕ парсера.

Зачем отдельно от eval. run_eval.py проверяет модель: что она вернула
на фразу. Эти два правила живут в handle.py и правят её ответ уже
после разбора — eval их не видит вовсе.

Оба появились из реальных ошибок бота:

  * лишняя неделя. 9 сентября (среда) «Вова Четверг сходить
    к ветеринару в 4.30» дало 17 сентября вместо 10-го;
  * перечисление дней. «В 4 часа дня, понедельник, вторник, среда,
    четверг, домашка, Севе, Глеб» давало то восемь задач, то две —
    в зависимости от контекста, а не от правил.

Третья проверка — распознавание расписания. Три дня и больше или слово
повтора означают правило недели, а не набор разовых дел. Порог невидим
для человека, поэтому ошибиться в нём легко, а заметить трудно: разница
проявится только через неделю, когда задачи не появятся снова.

Запуск:
    python3 tests/test_weekdays.py

Ни базы, ни сети, ни ключа API не нужно: обе функции чистые, из
handle.py берётся только их текст. Импортировать модуль целиком нельзя —
он тянет за собой db.py и подключение к PostgreSQL.
"""

import re
import sys
from datetime import date, timedelta
from pathlib import Path
from typing import Any, Dict, List, Optional

HANDLE = Path(__file__).parent.parent / "app" / "handle.py"


def load_rules() -> dict:
    """Выдёргивает блок правил из handle.py и исполняет его отдельно."""
    src = HANDLE.read_text(encoding="utf-8")
    start = src.index("WEEKDAY_WORDS = {")
    end = src.index("def _create_rules")
    ns = {"re": re, "date": date, "timedelta": timedelta,
          "Any": Any, "Dict": Dict, "List": List, "Optional": Optional}
    exec(src[start:end], ns)
    return ns


R = load_rules()
fix_date = R["_fix_weekday_date"]
expand = R["_expand_weekdays"]
rule_days = R["_rule_weekdays"]
subjects = R["_rule_subjects"]

WED = date(2026, 9, 9)    # среда
THU = date(2026, 9, 10)   # четверг

failures: List[str] = []


def check(name: str, got, want) -> None:
    if got == want:
        print(f"  ✓ {name}")
    else:
        print(f"  ✗ {name}\n      ждали:   {want}\n      вышло:   {got}")
        failures.append(name)


def task(assignee: Optional[str], day: Optional[str],
         title: str = "домашка") -> Dict[str, Any]:
    return {"title": title, "assignee": assignee, "date": day,
            "list": "scheduled" if day else "backlog", "time_start": "16:00"}


# ------------------------------------------------------------------
print("\nЛишняя неделя  (сегодня среда 09.09)")
# ------------------------------------------------------------------

check("боевая ошибка #27: четверг → завтра",
      fix_date("Вова Четверг сходить к ветеринару в 4.30", "2026-09-17", WED),
      "2026-09-10")

check("уже ближайший — не трогаем",
      fix_date("Севе теннис в четверг в 15:00", "2026-09-10", WED),
      "2026-09-10")

check("сегодняшний день недели → +7",
      fix_date("Глебу футбол в среду", "2026-09-16", WED),
      "2026-09-16")

check("точка это время, а не дата",
      fix_date("Сева матч в четверг 6.10", "2026-09-17", WED),
      "2026-09-10")

check("месяц словами — не трогаем",
      fix_date("матч в четверг 17 сентября", "2026-09-17", WED),
      "2026-09-17")

check("«через неделю» — не трогаем",
      fix_date("теннис в четверг через неделю", "2026-09-17", WED),
      "2026-09-17")

check("два дня — одиночное правило молчит",
      fix_date("свободен с четверга до субботы", "2026-09-17", WED),
      "2026-09-17")

check("день не совпал — не подменяем",
      fix_date("теннис в четверг", "2026-09-11", WED),
      "2026-09-11")

check("даты нет", fix_date("косить траву", None, WED), None)


# ------------------------------------------------------------------
print("\nПеречисление дней  (сегодня четверг 10.09)")
# ------------------------------------------------------------------

PHRASE = ("в 4 часа дня, понедельник, вторник, среда, четверг, "
          "домашка, Севе, Глеб")

two = [task("seva", "2026-09-14"), task("gleb", "2026-09-14")]
check("две задачи → восемь",
      [(t["date"], t["assignee"]) for t in expand(PHRASE, two, THU)],
      [("2026-09-14", "seva"), ("2026-09-14", "gleb"),
       ("2026-09-15", "seva"), ("2026-09-15", "gleb"),
       ("2026-09-16", "seva"), ("2026-09-16", "gleb"),
       ("2026-09-17", "seva"), ("2026-09-17", "gleb")])

eight = [task(a, d) for d in ("2026-09-14", "2026-09-15",
                              "2026-09-16", "2026-09-17")
         for a in ("seva", "gleb")]
check("модель уже разложила — не умножаем повторно",
      len(expand(PHRASE, eight, THU)), 8)

check("один день — размножения нет",
      len(expand("Севе теннис в четверг в 15:00",
                 [task("seva", "2026-09-17")], THU)), 1)

check("явная дата — не трогаем",
      len(expand("матч в четверг и пятницу 17 сентября",
                 [task("seva", "2026-09-17")], THU)), 1)

check("«через неделю» — не трогаем",
      len(expand("теннис в среду и четверг через неделю",
                 [task("seva", "2026-09-16")], THU)), 1)

mixed = [task("seva", "2026-09-14"), task(None, None, "косить траву")]
check("задача без даты не пропадает и не размножается",
      [(t["date"], t["title"]) for t in expand(PHRASE, mixed, THU)],
      [("2026-09-14", "домашка"), ("2026-09-15", "домашка"),
       ("2026-09-16", "домашка"), ("2026-09-17", "домашка"),
       (None, "косить траву")])

many = [task(a, "2026-09-14") for a in
        ("seva", "gleb", "kamilla", "vova", "sasha")] * 2
check("потолок: 10 задач × 4 дня — оставляем как есть",
      len(expand(PHRASE, many, THU)), 10)


# ------------------------------------------------------------------
print("\nРасписание или разовые дела")
# ------------------------------------------------------------------

dated = [task("seva", "2026-09-14")]
undated = [task(None, None, "косить траву")]

check("три дня → правило",
      rule_days("домашка понедельник среда четверг в 17:00", dated),
      [0, 2, 3])

check("четыре дня → правило",
      rule_days(PHRASE, dated), [0, 1, 2, 3])

check("два дня → разовые задачи",
      rule_days("теннис в среду и пятницу", dated), [])

check("два дня + «каждый» → правило",
      rule_days("каждую среду и пятницу теннис", dated), [2, 4])

check("один день + «по средам» → правило",
      rule_days("по средам бассейн в 18:00", dated), [2])

check("один день + «каждый вторник» → правило",
      rule_days("Севе музыка каждый вторник в 4", dated), [1])

check("один день без повтора → разовая",
      rule_days("Севе теннис в четверг в 15:00", dated), [])

check("recurring от парсера → правило",
      rule_days("Севе музыка во вторник в 16:00",
                [dict(task("seva", "2026-09-15"), recurring=True)]), [1])

check("та же фраза без recurring → разовая",
      rule_days("Севе музыка во вторник в 16:00",
                [task("seva", "2026-09-15")]), [])

check("три дня + месяц словами → разовые",
      rule_days("домашка понедельник среда четверг 17 сентября", dated), [])

check("три дня + «через неделю» → разовые",
      rule_days("домашка понедельник среда четверг через неделю", dated), [])

check("задача без даты → не правило",
      rule_days("каждый день чистить зубы", undated), [])

check("дней не названо → не правило",
      rule_days("каждый день проверять почту", dated), [])


# ------------------------------------------------------------------
print("\nОдно правило на человека")
# ------------------------------------------------------------------
#
# Модель часто сама раскладывает фразу по дням: «домашка ПН СР ЧТ Севе
# и Глебу» приходит шестью задачами. Правило описывает все дни сразу,
# поэтому шесть правил означали бы шесть расписаний вместо двух.

six = [task(a, d) for d in ("2026-09-14", "2026-09-16", "2026-09-17")
       for a in ("seva", "gleb")]
check("шесть задач от модели → два правила",
      [(t["title"], t["assignee"]) for t in subjects(six)],
      [("домашка", "seva"), ("домашка", "gleb")])

check("две задачи → два правила",
      len(subjects([task("seva", "2026-09-14"), task("gleb", "2026-09-14")])), 2)

check("одна задача → одно правило",
      len(subjects([task("seva", "2026-09-14")])), 1)

check("разные названия не склеиваются",
      len(subjects([task("seva", "2026-09-14", "теннис"),
                    task("seva", "2026-09-14", "музыка")])), 2)

check("порядок как во фразе",
      [t["assignee"] for t in subjects(six)], ["seva", "gleb"])


# ------------------------------------------------------------------
print()
if failures:
    print(f"ПРОВАЛЕНО: {len(failures)}")
    sys.exit(1)
print("Все проверки прошли.")
