-- ============================================================
-- 003 — отметки привычек по датам
-- ============================================================
--
-- Что делает: создаёт таблицу habit_marks. Существующие таблицы
-- не трогает, данные не меняет.
--
-- Зачем. Отметка «сделал сегодня» у привычек сначала жила в самой
-- клавиатуре сообщения: нажатая кнопка рисовалась с галочкой, и набор
-- отмеченных читался из подписей. Работало, пока сообщение одно —
-- но каждая новая команда «ежедневные» создаёт новое сообщение
-- с чистой клавиатурой, и галочки приходилось ставить заново.
--
-- Что эта таблица НЕ делает, намеренно:
--
--   * не меняет статус привычки. Она остаётся pending и приходит
--     завтра как обычно;
--   * не влияет на просрочку, напоминания и сводки. Ни один запрос,
--     кроме списка привычек, сюда не смотрит;
--   * не создаёт экземпляров задач по дням. Привычка по-прежнему
--     одна строка в tasks без даты.
--
-- То есть это по-прежнему мотиватор, а не учёт выполнения. Просто
-- теперь он не теряется при новом запросе и при перезапуске бота.
--
-- Первичный ключ из двух полей вместо отдельного id: отметка по своей
-- сути и есть пара «задача и день», второй раз за тот же день её
-- поставить нельзя. Повторное нажатие снимает отметку, то есть удаляет
-- строку, а не добавляет вторую.
--
-- ON DELETE CASCADE: убрал привычку — отметки уходят с ней. Держать
-- их не за чем, на статистику они не работают.
--
-- Транзакция не мешает: только CREATE TABLE, никаких ALTER TYPE.
--
-- Проверка результата:
--   psql -d familybot -c "\d habit_marks"
-- ============================================================

CREATE TABLE IF NOT EXISTS habit_marks (
    task_id    INTEGER NOT NULL REFERENCES tasks(id) ON DELETE CASCADE,
    mark_date  DATE    NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    PRIMARY KEY (task_id, mark_date)
);

-- Выборка всегда по дню: «что отмечено сегодня». Индекс по дате
-- нужен для чистки старых отметок, первичный ключ для неё не годится —
-- он начинается с task_id.
CREATE INDEX IF NOT EXISTS idx_habit_marks_date ON habit_marks (mark_date);
