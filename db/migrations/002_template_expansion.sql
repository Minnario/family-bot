-- ============================================================
-- 002 — развёртка шаблонов недели
-- ============================================================
--
-- Что делает:
--   1. Меняет в task_templates одиночный weekday на массив weekdays.
--   2. Добавляет уникальный индекс (template_id, date) в tasks.
--
-- Зачем. Таблица task_templates создана при проектировании и ни разу
-- не использовалась: правило «домашка по понедельникам» жить в ней
-- могло, но разворачивать его в задачи было нечем. Отсюда две проблемы,
-- которые решаются одним механизмом:
--
--   * у ежедневных нет галочки. Одна строка служит и правилом,
--     и экземпляром, поэтому complete_task() ставит done навсегда;
--   * перечисление дней даёт разовые задачи. «Домашка ПН-ЧТ» живёт
--     одну неделю и на следующей не появляется.
--
-- Массив вместо одного дня: одно правило — одна строка. При схеме
-- «строка на каждый день» правило «ПН-ЧТ» размазывалось бы по четырём
-- строкам, и пауза или удаление требовали четырёх действий.
--
-- Уникальный индекс — главная защита. Развёртка запускается по
-- расписанию и при старте бота, то есть одну и ту же дату увидит
-- много раз. Без индекса каждый запуск добавлял бы копии. Это тот же
-- приём, что idx_reminders_once для напоминаний.
--
-- Индекс намеренно НЕ частичный. У обычных задач template_id равен
-- NULL, а NULL в уникальном индексе не конфликтует сам с собой —
-- значит, они друг другу не мешают и без условия WHERE. Зато
-- ON CONFLICT (template_id, date) на полном индексе выводится
-- однозначно, а с частичным Postgres требует повторять его предикат.
--
-- Транзакция не мешает: ALTER TYPE здесь нет, только ALTER TABLE
-- и CREATE INDEX. Поэтому маркер no-transaction не нужен, и файл
-- пройдёт одной транзакцией — упадёт на середине, откатится целиком.
--
-- Проверка результата:
--   psql -d familybot -c "\d task_templates"
--   psql -d familybot -c "\d tasks"
-- ============================================================

-- Старое ограничение ссылалось на колонку, которой сейчас не станет.
ALTER TABLE task_templates DROP CONSTRAINT IF EXISTS weekday_valid;

ALTER TABLE task_templates ADD COLUMN IF NOT EXISTS weekdays SMALLINT[];

-- Таблица пустая, но перенос описан явно: если строки всё же есть,
-- одиночный день превращается в массив из одного элемента.
UPDATE task_templates SET weekdays = ARRAY[weekday]::SMALLINT[]
 WHERE weekdays IS NULL;

ALTER TABLE task_templates ALTER COLUMN weekdays SET NOT NULL;
ALTER TABLE task_templates DROP COLUMN IF EXISTS weekday;

-- 0 = понедельник, 6 = воскресенье. Пустой массив бессмыслен, больше
-- семи дней невозможно.
ALTER TABLE task_templates ADD CONSTRAINT weekdays_valid CHECK (
    array_length(weekdays, 1) BETWEEN 1 AND 7
    AND weekdays <@ ARRAY[0, 1, 2, 3, 4, 5, 6]::SMALLINT[]
);

CREATE UNIQUE INDEX IF NOT EXISTS idx_tasks_template_once
    ON tasks (template_id, date);
